export const supportedLocales = ["en", "sr-Latn", "sr-Cyrl"] as const;
export type Locale = (typeof supportedLocales)[number];

export const defaultLocale: Locale = "en";

export const localeOptions: Array<{ value: Locale; label: string }> = [
  { value: "en", label: "EN" },
  { value: "sr-Latn", label: "SR-LAT" },
  { value: "sr-Cyrl", label: "SR-CYR" },
];

export const normalizeLocale = (value?: string | null): Locale => {
  if (!value) return defaultLocale;
  if (value === "sr") return "sr-Latn";
  return supportedLocales.includes(value as Locale) ? (value as Locale) : defaultLocale;
};

